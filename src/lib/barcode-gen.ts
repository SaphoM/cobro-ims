import { randomInt } from 'crypto';

/**
 * Generates internal EAN-13 barcodes for products that don't arrive with a
 * manufacturer/supplier barcode.
 *
 * Format: 200 + 9 random digits + 1 EAN-13 check digit = 13 characters.
 *
 * The "200" prefix is within the EAN-13 in-store/internal-use range (200–299),
 * which is globally reserved and will never be registered to an external GS1
 * member. Generated barcodes cannot collide with any real supplier barcode.
 *
 * The 9-digit body gives 10^9 possible values — with fewer than a million
 * products the collision probability per generation attempt is negligible.
 * A retry loop guards against the (astronomically unlikely) case where the
 * random value happens to match an existing barcode.
 */

const INTERNAL_PREFIX = '200';

/** Compute the EAN-13 check digit for a 12-digit string. */
function ean13CheckDigit(digits12: string): string {
  let sum = 0;
  for (let i = 0; i < 12; i++) {
    // EAN-13: odd positions (0-indexed: 0,2,4,...) × 1, even positions × 3
    sum += parseInt(digits12[i], 10) * (i % 2 === 0 ? 1 : 3);
  }
  return String((10 - (sum % 10)) % 10);
}

/**
 * Generate a unique 13-digit EAN-13 barcode not already in `existingBarcodes`.
 * Throws only when 50 consecutive attempts all collide — not a realistic
 * scenario in any production catalogue.
 */
export function generateUniqueBarcode(existingBarcodes: ReadonlySet<string>): string {
  for (let attempt = 0; attempt < 50; attempt++) {
    let body = '';
    for (let i = 0; i < 9; i++) body += randomInt(0, 10).toString();
    const digits12 = INTERNAL_PREFIX + body;
    const barcode = digits12 + ean13CheckDigit(digits12);
    if (!existingBarcodes.has(barcode)) return barcode;
  }
  throw new Error(
    'Could not generate a unique barcode after 50 attempts — please supply one manually.'
  );
}

/** True when `s` is a valid 13-digit EAN-13 number (check digit passes). */
export function isValidEan13(s: string): boolean {
  if (!/^\d{13}$/.test(s)) return false;
  return ean13CheckDigit(s.slice(0, 12)) === s[12];
}

/** True when `barcode` was auto-generated by this system (200-prefix). */
export function isInternalBarcode(barcode: string): boolean {
  return barcode.startsWith(INTERNAL_PREFIX) && barcode.length === 13;
}
