/**
 * The original repositories use Node's `randomUUID` from 'crypto'. In the
 * browser the equivalent is `crypto.randomUUID()`, which exists in every
 * modern engine but only in a *secure context* (https, or localhost). A
 * static site served over plain http on a LAN IP would not have it, so this
 * falls back to `getRandomValues` (always available) formatted as a v4 UUID,
 * and finally to Math.random for ancient engines. IDs are opaque keys here —
 * nothing depends on their cryptographic quality.
 */
export function randomUUID(): string {
  if (typeof crypto !== 'undefined' && typeof crypto.randomUUID === 'function') {
    return crypto.randomUUID();
  }
  if (typeof crypto !== 'undefined' && typeof crypto.getRandomValues === 'function') {
    const bytes = crypto.getRandomValues(new Uint8Array(16));
    bytes[6] = (bytes[6] & 0x0f) | 0x40; // version 4
    bytes[8] = (bytes[8] & 0x3f) | 0x80; // variant 10
    const hex = [...bytes].map((b) => b.toString(16).padStart(2, '0')).join('');
    return `${hex.slice(0, 8)}-${hex.slice(8, 12)}-${hex.slice(12, 16)}-${hex.slice(16, 20)}-${hex.slice(20)}`;
  }
  return 'xxxxxxxx-xxxx-4xxx-yxxx-xxxxxxxxxxxx'.replace(/[xy]/g, (c) => {
    const r = (Math.random() * 16) | 0;
    return (c === 'x' ? r : (r & 0x3) | 0x8).toString(16);
  });
}
