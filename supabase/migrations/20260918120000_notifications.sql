-- Persisted notifications — the app previously had no notifications table at
-- all (see src/lib/notifications.ts's old header comment): the header bell
-- recomputed ephemeral "what needs attention right now" counts live on every
-- render, with no created_at, no read/unread state, and nothing surviving a
-- state change. That's still fine for pure gauges (low stock count, pending
-- approvals count), but the Stores return reminder needs to be a real,
-- individually addressable, auditable event: one row per requisition, a
-- fixed creation timestamp, and a read_at that's set once and never un-set.
--
-- One notification type only for now (return_reminder) - this is the first
-- real notification record in the app, not a second competing system.

create table notifications (
  id uuid primary key default gen_random_uuid(),
  user_id uuid not null references users(id) on delete cascade,
  type text not null check (type in ('return_reminder')),
  sales_order_id uuid references sales_orders(id) on delete cascade,
  title text not null,
  message text not null,
  href text,
  created_at timestamptz not null default now(),
  read_at timestamptz
);

create index notifications_user_id_idx on notifications (user_id, created_at desc);

-- One reminder per (user, requisition) ever - the sweep that generates these
-- (src/lib/services/reminder-generation.ts) runs on ordinary page loads
-- rather than a schedule (this app has no cron/edge-function runtime - see
-- docs/ARCHITECTURE.md), so it may run many times after the 8-hour
-- threshold is crossed. This index is what makes that idempotent instead of
-- spamming duplicate reminders.
create unique index notifications_return_reminder_once
  on notifications (user_id, sales_order_id)
  where type = 'return_reminder';

alter table notifications enable row level security;

-- A user only ever reads or updates (marks read) their own notifications.
create policy notifications_select_own on notifications
  for select using (user_id = auth.uid());

create policy notifications_update_own on notifications
  for update using (user_id = auth.uid())
  with check (user_id = auth.uid());

-- Deliberately NO insert policy for the authenticated role: a notification
-- is frequently generated by someone other than its recipient (e.g. Stores
-- loading their dashboard triggers a reminder addressed to an Engineer), so
-- self-authored-insert (the pattern used elsewhere in this schema - see
-- 20260916160000_self_authored_update_insert_policies.sql) doesn't fit.
-- Creation goes through the service-role client instead (src/lib/supabase/
-- service.ts), which bypasses RLS by design for exactly this kind of
-- privileged, cross-user, system-generated write.
